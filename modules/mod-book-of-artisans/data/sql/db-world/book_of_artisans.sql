-- 4b. The list: the professions, and the recipes their trainers teach
-- ---------------------------------------------------------------------------
-- The full book teaches what a profession trainer teaches: the rows that learn a trade and raise
-- its ceiling, and the recipes of every trade (#5818). The window is filtered to what the character
-- can train (ONLY_TRAINABLE_ROWS in the module), so a recipe shows only for a trade the character
-- knows and once their skill reaches the recipe's requirement - the same rows, the same
-- requirements and the same prices a placed trainer would show. The realm's original 200001 held
