-- Grand Master - plus CoA's own: Woodcutting and Woodworking down to Artisan, and Bushcraft as a
-- single grant. The book is the only place that teaches some of them: Bushcraft's single grant, and
-- every rank of Woodcutting and Woodworking up to Artisan, sit on no other trainer in the realm.
--
-- The recipe rows follow them: every spell a profession trainer (`trainer`.`Type` 2) teaches under
-- First Aid, Blacksmithing, Leatherworking, Alchemy, Cooking, Mining, Tailoring, Engineering,
-- Enchanting, Jewelcrafting or Inscription, each with the lowest skill, level and cost any of those
